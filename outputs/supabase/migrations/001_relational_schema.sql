create or replace function public.replace_store_shipping_rates(p_rates jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_rate record;
begin
  if coalesce(jsonb_typeof(p_rates) <> 'object', true) or jsonb_object_length(p_rates) > 40 then
    raise exception using errcode = '22023', message = 'INVALID_SHIPPING_RATES';
  end if;

  delete from public.shipping_rates;
  for v_rate in select key, value from jsonb_each_text(p_rates) loop
    if length(v_rate.key) = 0 or length(v_rate.key) > 60 or v_rate.value::numeric < 0 or v_rate.value::numeric > 100000 then
      raise exception using errcode = '22023', message = 'INVALID_SHIPPING_RATES';
    end if;
    insert into public.shipping_rates(governorate, fee_egp, updated_at)
    values (v_rate.key, v_rate.value::numeric, now());
  end loop;
end;
$$;

create or replace function public.create_store_order(p_order jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id text := p_order->>'id';
  v_phone text := p_order->>'phone';
  v_phone_normalized text := regexp_replace(coalesce(p_order->>'phone', ''), '\D', '', 'g');
  v_customer_id text;
  v_item jsonb;
  v_product public.products%rowtype;
  v_product_id text;
  v_quantity integer;
  v_unit_price numeric(12, 2);
  v_subtotal numeric(12, 2) := 0;
  v_shipping_fee numeric(12, 2);
  v_total numeric(12, 2);
  v_has_unpriced_item boolean := false;
  v_order public.orders%rowtype;
begin
  if v_id is null or length(v_id) = 0 or length(v_phone_normalized) < 7
    or coalesce(jsonb_typeof(p_order->'items') <> 'array', true)
    or jsonb_array_length(coalesce(p_order->'items', '[]'::jsonb)) not between 1 and 12 then
    raise exception using errcode = '22023', message = 'INVALID_ORDER';
  end if;

  select c.id into v_customer_id from public.customers c where c.phone_normalized = v_phone_normalized;

  insert into public.orders(
    id, customer_id, status, customer_name, customer_phone, governorate, city,
    address, notes, payment_note, created_at, updated_at
  ) values (
    v_id, v_customer_id, 'جديد', p_order->>'name', v_phone, p_order->>'governorate',
    p_order->>'city', p_order->>'address', coalesce(p_order->>'notes', ''),
    'السعر وطريقة الدفع يتأكدوا مع العميل قبل الشحن', now(), now()
  ) returning * into v_order;

  for v_item in select value from jsonb_array_elements(p_order->'items') loop
    v_product_id := coalesce(v_item->>'productId', '');
    if left(v_product_id, 5) = 'item-' then
      v_product_id := 'taager-' || substr(v_product_id, 6);
    end if;
    v_quantity := nullif(v_item->>'quantity', '')::integer;
    if v_quantity is null or v_quantity < 1 or v_quantity > 20 then
      raise exception using errcode = '22023', message = 'INVALID_ORDER_ITEM';
    end if;

    select p.* into v_product from public.products p where p.id = v_product_id and p.active for share;
    if not found then
      raise exception using errcode = 'P0002', message = 'PRODUCT_NOT_FOUND';
    end if;
    if v_product.stock is not null and v_quantity > v_product.stock then
      raise exception using errcode = 'P0001', message = 'INSUFFICIENT_STOCK';
    end if;

    if v_product.price_egp is null then
      v_unit_price := null;
      v_has_unpriced_item := true;
    else
      v_unit_price := round(v_product.price_egp * (1 - v_product.discount_percent / 100), 2);
      v_subtotal := v_subtotal + v_unit_price * v_quantity;
    end if;

    insert into public.order_items(
      order_id, product_id, product_name, quantity, unit_price_egp,
      original_unit_price_egp, discount_percent
    ) values (
      v_id, v_product.id, v_product.name, v_quantity, v_unit_price,
      v_product.price_egp, v_product.discount_percent
    );
  end loop;

  if v_has_unpriced_item then v_subtotal := null; end if;
  select r.fee_egp into v_shipping_fee from public.shipping_rates r where r.governorate = p_order->>'governorate';
  if v_subtotal is not null and v_shipping_fee is not null then v_total := v_subtotal + v_shipping_fee; end if;

  update public.orders o set subtotal_egp = v_subtotal, shipping_fee_egp = v_shipping_fee,
    total_egp = v_total, updated_at = now() where o.id = v_id returning o.* into v_order;
  insert into public.order_status_events(order_id, status, actor) values (v_id, 'جديد', 'system');
  return to_jsonb(v_order);
end;
$$;

