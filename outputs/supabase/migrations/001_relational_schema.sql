-- Atomic status transitions preserve the existing policy: adjust stock only
-- when an order becomes complete, then reverse the movement when it leaves
-- complete or is cancelled. Row locks and the inventory_adjusted flag prevent
-- concurrent duplicate adjustments.
create or replace function public.set_store_order_status(p_order_id text, p_status text)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
  v_item record;
  v_stock integer;
  v_previous_status text;
begin
  if p_status is null or p_status not in ('جديد', 'تم التأكيد', 'جاري التجهيز', 'تم الشحن', 'مكتمل', 'ملغي') then
    raise exception using errcode = '22023', message = 'INVALID_ORDER_STATUS';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception using errcode = 'P0002', message = 'ORDER_NOT_FOUND';
  end if;
  v_previous_status := v_order.status;

  if p_status = 'مكتمل' and v_order.status <> 'مكتمل' and not v_order.inventory_adjusted then
    for v_item in
      select oi.product_id, sum(oi.quantity)::integer as quantity
      from public.order_items oi
      where oi.order_id = p_order_id and oi.product_id is not null
      group by oi.product_id
      order by oi.product_id
    loop
      select p.stock into v_stock from public.products p where p.id = v_item.product_id for update;
      if found and v_stock is not null and v_stock < v_item.quantity then
        raise exception using errcode = 'P0001', message = 'INSUFFICIENT_STOCK';
      end if;
    end loop;

    for v_item in
      select oi.product_id, sum(oi.quantity)::integer as quantity
      from public.order_items oi
      where oi.order_id = p_order_id and oi.product_id is not null
      group by oi.product_id
      order by oi.product_id
    loop
      update public.products p
      set stock = p.stock - v_item.quantity, updated_at = now()
      where p.id = v_item.product_id and p.stock is not null;

      if found then
        insert into public.inventory_movements(product_id, order_id, movement_type, quantity_delta)
        values (v_item.product_id, p_order_id, 'sale', -v_item.quantity);
      end if;
    end loop;
    v_order.inventory_adjusted := true;
  elsif v_order.inventory_adjusted
    and (p_status = 'ملغي' or (v_order.status = 'مكتمل' and p_status <> 'مكتمل')) then
    for v_item in
      select oi.product_id, sum(oi.quantity)::integer as quantity
      from public.order_items oi
      where oi.order_id = p_order_id and oi.product_id is not null
      group by oi.product_id
      order by oi.product_id
    loop
      update public.products p
      set stock = p.stock + v_item.quantity, updated_at = now()
      where p.id = v_item.product_id and p.stock is not null;

      if found then
        insert into public.inventory_movements(product_id, order_id, movement_type, quantity_delta)
        values (v_item.product_id, p_order_id, 'restock', v_item.quantity);
      end if;
    end loop;
    v_order.inventory_adjusted := false;
  end if;

  update public.orders o
  set status = p_status, inventory_adjusted = v_order.inventory_adjusted, updated_at = now()
  where o.id = p_order_id
  returning o.* into v_order;

  if v_order.status is distinct from v_previous_status then
    insert into public.order_status_events(order_id, status, actor)
    values (p_order_id, p_status, 'admin');
  end if;

  return to_jsonb(v_order);
end;
$$;

create or replace function public.consume_store_rate_limit(p_bucket_key text, p_limit integer, p_window_seconds integer)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_hits integer;
begin
  if p_bucket_key is null or p_limit < 1 or p_window_seconds < 1 then
    raise exception using errcode = '22023', message = 'INVALID_RATE_LIMIT';
  end if;

  delete from public.store_rate_limits
  where window_started_at < now() - interval '24 hours';

  insert into public.store_rate_limits(bucket_key, hit_count, window_started_at)
  values (p_bucket_key, 1, now())
  on conflict (bucket_key) do update set
    hit_count = case
      when public.store_rate_limits.window_started_at <= now() - make_interval(secs => p_window_seconds) then 1
      else public.store_rate_limits.hit_count + 1
    end,
    window_started_at = case
      when public.store_rate_limits.window_started_at <= now() - make_interval(secs => p_window_seconds) then now()
      else public.store_rate_limits.window_started_at
    end
  returning hit_count into v_hits;

  return v_hits <= p_limit;
end;
$$;

