-- Additive schema for the relational store rollout.
-- This migration intentionally keeps public.store_records for export/rollback.

create table if not exists public.products (
  id text primary key,
  name text not null check (char_length(name) between 2 and 100),
  category text not null check (char_length(category) between 1 and 40),
  description text not null default '',
  badge text not null default '',
  image text not null default '',
  price_egp numeric(12, 2) check (price_egp is null or price_egp between 0 and 100000000),
  base_price_egp numeric(12, 2) check (base_price_egp is null or base_price_egp between 0 and 100000000),
  source text not null default '',
  source_listed_price_egp numeric(12, 2) check (source_listed_price_egp is null or source_listed_price_egp between 0 and 100000000),
  source_listed_discount numeric(7, 2) check (source_listed_discount is null or source_listed_discount between 0 and 100),
  stock integer check (stock is null or stock between 0 and 10000000),
  discount_percent numeric(5, 2) not null default 0 check (discount_percent between 0 and 100),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.product_images (
  id bigint generated by default as identity primary key,
  product_id text not null references public.products(id) on delete cascade,
  image_url text not null,
  position integer not null default 0 check (position >= 0),
  unique (product_id, image_url)
);

create table if not exists public.customers (
  id text primary key,
  name text not null check (char_length(name) between 2 and 80),
  phone text not null,
  phone_normalized text not null unique,
  password_salt text not null,
  password_hash text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customer_addresses (
  id bigint generated by default as identity primary key,
  customer_id text not null references public.customers(id) on delete cascade,
  governorate text not null check (char_length(governorate) between 1 and 60),
  city text not null check (char_length(city) between 1 and 80),
  address text not null check (char_length(address) between 8 and 500),
  is_default boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists customer_addresses_one_default
  on public.customer_addresses(customer_id) where is_default;

create table if not exists public.shipping_rates (
  governorate text primary key check (char_length(governorate) between 1 and 60),
  fee_egp numeric(12, 2) not null check (fee_egp between 0 and 100000),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id text primary key,
  customer_id text references public.customers(id) on delete set null,
  status text not null default 'جديد'
    check (status in ('جديد', 'تم التأكيد', 'جاري التجهيز', 'تم الشحن', 'مكتمل', 'ملغي')),
  customer_name text not null check (char_length(customer_name) between 2 and 80),
  customer_phone text not null,
  governorate text not null,
  city text not null,
  address text not null,
  notes text not null default '',
  subtotal_egp numeric(12, 2),
  shipping_fee_egp numeric(12, 2),
  total_egp numeric(12, 2),
  payment_note text not null default 'السعر وطريقة الدفع يتأكدوا مع العميل قبل الشحن',
  inventory_adjusted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_created_at_desc on public.orders(created_at desc);
create index if not exists orders_status_created_at on public.orders(status, created_at desc);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on delete cascade,
  product_id text references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity between 1 and 20),
  unit_price_egp numeric(12, 2),
  original_unit_price_egp numeric(12, 2),
  discount_percent numeric(5, 2) not null default 0 check (discount_percent between 0 and 100)
);

create index if not exists order_items_order_id on public.order_items(order_id);

create table if not exists public.order_status_events (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on delete cascade,
  status text not null check (status in ('جديد', 'تم التأكيد', 'جاري التجهيز', 'تم الشحن', 'مكتمل', 'ملغي')),
  actor text not null default 'admin',
  created_at timestamptz not null default now()
);

create index if not exists order_status_events_order_id on public.order_status_events(order_id, created_at);

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  product_id text not null references public.products(id) on delete restrict,
  order_id text references public.orders(id) on delete set null,
  movement_type text not null check (movement_type in ('sale', 'restock', 'adjustment')),
  quantity_delta integer not null check (quantity_delta <> 0),
  created_at timestamptz not null default now()
);

create index if not exists inventory_movements_product_id on public.inventory_movements(product_id, created_at desc);

create table if not exists public.price_inquiries (
  id text primary key,
  product_id text references public.products(id) on delete set null,
  product_name text not null,
  customer_name text not null check (char_length(customer_name) between 2 and 80),
  customer_phone text not null,
  message text not null default '',
  status text not null default 'جديد' check (status in ('جديد', 'تم التواصل')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists price_inquiries_status_created_at
  on public.price_inquiries(status, created_at desc);

create table if not exists public.store_rate_limits (
  bucket_key text primary key,
  hit_count integer not null check (hit_count > 0),
  window_started_at timestamptz not null
);

create index if not exists store_rate_limits_window_started_at
  on public.store_rate_limits(window_started_at);

create or replace function public.upsert_store_product(p_product jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id text := p_product->>'id';
  v_image jsonb;
  v_position integer := 0;
begin
  if v_id is null or length(v_id) = 0 then
    raise exception using errcode = '22023', message = 'INVALID_PRODUCT_ID';
  end if;

  insert into public.products (
    id, name, category, description, badge, image, price_egp, base_price_egp,
    source, source_listed_price_egp, source_listed_discount, stock,
    discount_percent, active, updated_at
  ) values (
    v_id, p_product->>'name', p_product->>'category', coalesce(p_product->>'description', ''),
    coalesce(p_product->>'badge', ''), coalesce(p_product->>'image', ''),
    nullif(p_product->>'price', '')::numeric, nullif(p_product->>'basePrice', '')::numeric,
    coalesce(p_product->>'source', ''), nullif(p_product->>'sourceListedPrice', '')::numeric,
    nullif(p_product->>'sourceListedDiscount', '')::numeric, nullif(p_product->>'stock', '')::integer,
    coalesce(nullif(p_product->>'discount', '')::numeric, 0),
    coalesce((p_product->>'active')::boolean, true), now()
  )
  on conflict (id) do update set
    name = excluded.name, category = excluded.category, description = excluded.description,
    badge = excluded.badge, image = excluded.image, price_egp = excluded.price_egp,
    base_price_egp = excluded.base_price_egp, source = excluded.source,
    source_listed_price_egp = excluded.source_listed_price_egp,
    source_listed_discount = excluded.source_listed_discount,
    stock = excluded.stock, discount_percent = excluded.discount_percent,
    active = excluded.active, updated_at = now();

  delete from public.product_images where product_id = v_id;
  if jsonb_typeof(p_product->'images') = 'array' then
    for v_image in select value from jsonb_array_elements(p_product->'images') loop
      if jsonb_typeof(v_image) = 'string' and length(trim(both '"' from v_image::text)) > 0 then
        insert into public.product_images(product_id, image_url, position)
        values (v_id, v_image #>> '{}', v_position)
        on conflict (product_id, image_url) do update set position = excluded.position;
        v_position := v_position + 1;
      end if;
    end loop;
  end if;
end;
$$;

create or replace function public.upsert_store_products(p_products jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_product jsonb;
begin
  if coalesce(jsonb_typeof(p_products) <> 'array', true) then
    raise exception using errcode = '22023', message = 'INVALID_PRODUCTS';
  end if;
  for v_product in select value from jsonb_array_elements(p_products) loop
    perform public.upsert_store_product(v_product);
  end loop;
end;
$$;

create or replace function public.upsert_store_customer(p_customer jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id text := p_customer->>'id';
  v_phone text := p_customer->>'phone';
  v_phone_normalized text := regexp_replace(coalesce(p_customer->>'phone', ''), '\D', '', 'g');
begin
  if v_id is null or length(v_id) = 0 or length(v_phone_normalized) < 7 then
    raise exception using errcode = '22023', message = 'INVALID_CUSTOMER';
  end if;

  insert into public.customers(id, name, phone, phone_normalized, password_salt, password_hash, updated_at)
  values (v_id, p_customer->>'name', v_phone, v_phone_normalized,
    p_customer->>'passwordSalt', p_customer->>'passwordHash', now())
  on conflict (id) do update set
    name = excluded.name, phone = excluded.phone, phone_normalized = excluded.phone_normalized,
    password_salt = excluded.password_salt, password_hash = excluded.password_hash, updated_at = now();

  if coalesce(p_customer->>'governorate', '') <> ''
    and coalesce(p_customer->>'city', '') <> ''
    and coalesce(p_customer->>'address', '') <> '' then
    insert into public.customer_addresses(customer_id, governorate, city, address, is_default, updated_at)
    values (v_id, p_customer->>'governorate', p_customer->>'city', p_customer->>'address', true, now())
    on conflict (customer_id) where is_default do update set
      governorate = excluded.governorate, city = excluded.city,
      address = excluded.address, updated_at = now();
  end if;
end;
$$;

